// Shared date and data helpers for the Node scripts.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const DATA_JS = join(ROOT, 'data', 'earnings.js');
const PREFIX = 'window.EARNINGS = ';

export const config = JSON.parse(readFileSync(join(ROOT, 'config.json'), 'utf8'));

// Dates as 'YYYY-MM-DD' in UTC so the runner's time zone doesn't matter.
export const iso = (d) => d.toISOString().slice(0, 10);
export const parseIso = (s) => new Date(`${s}T00:00:00Z`);
export const addDays = (d, n) => new Date(d.getTime() + n * 86400000);

// A YYYY-MM-DD argument as a Monday, or an error for anything else (it reaches the scripts from workflow inputs).
export function parseWeekArg(s) {
  const d = parseIso(s ?? '');
  if (!/^\d{4}-\d{2}-\d{2}$/.test(s ?? '') || Number.isNaN(d.getTime()) || iso(d) !== s) {
    throw new Error(`Expected a date as YYYY-MM-DD, got "${s}"`);
  }
  return mondayOf(d);
}

// "$1,234.5" → 1234.5, "($0.12)" or "-$0.12" → -0.12, "N/A" or "" → null.
export function money(s) {
  if (!s || /n\/a/i.test(s) || !/\d/.test(s)) return null;
  const v = Number(s.replace(/[^0-9.]/g, ''));
  if (!Number.isFinite(v)) return null;
  return s.includes('(') || s.includes('-') ? -v : v;
}

const TIME = { 'time-pre-market': 'bmo', 'time-after-hours': 'amc' };

// Nasdaq calendar rows → compact rows, largest market cap first.
export function parseRows(rows) {
  return (rows ?? []).filter((r) => r?.symbol).map((r) => ({
    s: r.symbol.trim(),
    n: (r.name ?? '').trim(),
    t: TIME[r.time] ?? 'tns',
    mc: money(r.marketCap),
    eps: money(r.epsForecast),
    ly: money(r.lastYearEPS),
    q: r.fiscalQuarterEnding || null,
    ne: Number(r.noOfEsts) || null,
  })).sort((a, b) => (b.mc ?? 0) - (a.mc ?? 0));
}

export function mondayOf(d) {
  const dow = (d.getUTCDay() + 6) % 7; // Mon = 0
  return addDays(new Date(Date.UTC(d.getUTCFullYear(), d.getUTCMonth(), d.getUTCDate())), -dow);
}

// On weekends, "this week" means the coming week.
export function focusMonday(now = new Date()) {
  const dow = now.getUTCDay();
  const m = mondayOf(now);
  return dow === 0 || dow === 6 ? addDays(m, 7) : m;
}

// data/earnings.js is both the browser's data (a script, so index.html opens straight from disk) and the
// scripts' store. One company per line keeps the daily data commits small.
export function loadData() {
  if (!existsSync(DATA_JS)) return { updated: null, days: {} };
  const text = readFileSync(DATA_JS, 'utf8').trim();
  return JSON.parse(text.slice(PREFIX.length, text.endsWith(';') ? -1 : undefined));
}

export function serialize(data) {
  const days = Object.entries(data.days).map(([date, rows]) =>
    `${JSON.stringify(date)}:[${rows.length ? `\n${rows.map((r) => JSON.stringify(r)).join(',\n')}\n` : ''}]`);
  return `${PREFIX}{"updated":${JSON.stringify(data.updated)},"days":{\n${days.join(',\n')}\n}};\n`;
}

export function saveData(data) {
  writeFileSync(DATA_JS, serialize(data));
  const { perSession, watchlist, logoOverrides = {} } = config;
  writeFileSync(join(ROOT, 'config.js'),
    `// Generated by the scripts from config.json — do not edit by hand.\nwindow.CONFIG = ${JSON.stringify({ perSession, watchlist, logoOverrides })};\n`);
}
